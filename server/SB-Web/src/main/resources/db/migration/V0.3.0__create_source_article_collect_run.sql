-- 수집 출처 · 기사 · 수집 기록 (enum 컬럼은 varchar + 이름 문자열, 시각은 timestamptz)
-- created_at/updated_at: BaseEntity(LocalDateTime, 서울 시각)와 맞추려고 서울 시각 기본값 (JPA 밖 insert 대비)

create table source (
    id                 bigint generated by default as identity primary key,
    code               varchar(50)   not null unique,
    display_name       varchar(100)  not null,
    -- ArticleKind: NEWS, ADVISORY, VULNERABILITY
    kind               varchar(32)   not null,
    -- ArticleRegion: DOMESTIC, OVERSEAS
    region             varchar(16)   not null,
    -- FeedFormat: RSS, CISA_KEV_JSON, NVD_API, GHSA_API (수집기 선택 기준)
    feed_format        varchar(32)   not null,
    feed_url           varchar(1000) not null,
    interval_minutes   int           not null,
    is_enabled         boolean       not null default true,
    -- 마지막 성공 수집 시각 (실패는 갱신 안 함)
    last_collected_at  timestamptz,
    -- CollectStatus: SUCCESS, FAILED
    last_status        varchar(16),
    created_at         timestamp     not null default (now() at time zone 'Asia/Seoul'),
    updated_at         timestamp     not null default (now() at time zone 'Asia/Seoul')
);

create table article (
    id                         bigint generated by default as identity primary key,
    source_id                  bigint        not null references source (id),
    kind                       varchar(32)   not null,
    title                      varchar(500)  not null,
    translated_title           varchar(500),
    original_url               varchar(1000) not null unique,
    publisher_name             varchar(100)  not null,
    published_at               timestamptz   not null,
    -- 출처가 게시일을 안 주거나 미래 시각이라 수집 시각으로 대체함
    is_published_at_estimated  boolean       not null default false,
    region                     varchar(16)   not null,
    -- ArticleTopic 이름 (VULNERABILITY, RANSOMWARE, PRIVACY, REMOTE_ACCESS, DATABASE, SUPPLY_CHAIN, POLICY, GENERAL)
    topic                      varchar(32)   not null default 'GENERAL',
    -- AiStatus: PENDING, DONE, FAILED
    ai_status                  varchar(16)   not null default 'PENDING',
    ai_attempt_count           int           not null default 0,
    -- CVE 항목만 값 있음 (null 은 유일 제약에서 제외)
    cve_id                     varchar(32)   unique,
    cvss_score                 numeric(3, 1),
    -- 점수 버전: 3.1 우선, 없으면 4.0
    cvss_version               varchar(8),
    is_kev                     boolean       not null default false,
    is_urgent                  boolean       not null default false,
    collected_at               timestamptz   not null,
    created_at                 timestamp     not null default (now() at time zone 'Asia/Seoul'),
    updated_at                 timestamp     not null default (now() at time zone 'Asia/Seoul')
);

-- 목록 최신순 / 종류·지역별 최신순 / AI 처리 대기열
create index idx_article_published_at_id on article (published_at desc, id desc);
create index idx_article_kind_region_published_at on article (kind, region, published_at desc);
create index idx_article_ai_status_id on article (ai_status, id);

create table collect_run (
    id             bigint generated by default as identity primary key,
    source_id      bigint       not null references source (id),
    started_at     timestamptz  not null,
    -- 완료 전에는 finished_at, status 가 null
    finished_at    timestamptz,
    status         varchar(16),
    new_count      int          not null default 0,
    error_code     varchar(64),
    -- 정리된 값 (제어문자 제거, 500자 이내)
    error_message  varchar(500)
);

-- 출처별 최근 수집 시도 조회
create index idx_collect_run_source_started_at on collect_run (source_id, started_at desc);

