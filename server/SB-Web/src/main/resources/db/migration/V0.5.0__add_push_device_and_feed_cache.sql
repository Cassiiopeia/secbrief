-- 조건부 수집(피드 캐시 검증값) · 긴급 알림 발송 표시 · 푸시 기기 (#33)

-- 출처가 준 캐시 검증값: 다음 수집에 If-None-Match / If-Modified-Since 로 보냄 (304 면 내려받지 않음)
alter table source
    add column feed_etag           varchar(255),
    add column feed_last_modified  varchar(64);

-- 긴급 알림 발송 처리 시각 (null: 아직 알림 대상, 받을 기기가 없어도 처리하면 채움)
alter table article
    add column urgent_notified_at  timestamptz;

-- 알림 기능 이전에 쌓인 긴급 기사는 발송하지 않음
update article set urgent_notified_at = now() where is_urgent = true;

-- 알림 대기열: 긴급이고 아직 발송 안 한 기사
create index idx_article_urgent_unnotified on article (id) where is_urgent = true and urgent_notified_at is null;

-- 알림을 켠 기기 (회원 없음: 푸시 토큰이 곧 기기 식별값, 종류를 모두 끄면 행 삭제)
create table push_device (
    id           bigint generated by default as identity primary key,
    -- Expo 푸시 토큰 (ExponentPushToken[...])
    push_token   varchar(255) not null unique,
    -- PushPlatform: ANDROID, IOS
    platform     varchar(16)  not null,
    created_at   timestamp    not null default (now() at time zone 'Asia/Seoul'),
    updated_at   timestamp    not null default (now() at time zone 'Asia/Seoul')
);

-- 기기가 켠 알림 종류 (AlertCategory: KISA_URGENT, KEV, CRITICAL_CVE)
create table push_device_alert_category (
    push_device_id  bigint      not null references push_device (id) on delete cascade,
    alert_category  varchar(32) not null,
    primary key (push_device_id, alert_category)
);

-- 발송 접수증 대기: 발송 뒤 받은 티켓 (접수증 확인 후 삭제, 무효 토큰이면 기기도 삭제)
create table push_ticket (
    id              bigint generated by default as identity primary key,
    push_device_id  bigint       not null references push_device (id) on delete cascade,
    ticket_id       varchar(64)  not null,
    sent_at         timestamptz  not null
);

create index idx_push_ticket_sent_at on push_ticket (sent_at);

-- 기사 대표 이미지: 피드가 준 이미지 주소 > 내려받아 줄인 사본을 자체 저장소(MinIO)에 보관
alter table article
    -- 피드가 준 원본 이미지 주소 (없으면 null)
    add column image_source_url     varchar(1000),
    -- 저장소 객체 키 (STORED 일 때만 값 있음)
    add column image_object_key     varchar(200),
    -- ImageStatus: NONE(이미지 없음), PENDING(저장 대기), STORED, FAILED
    add column image_status         varchar(16) not null default 'NONE',
    add column image_attempt_count  int         not null default 0;

-- 이미지 저장 대기열
create index idx_article_image_pending on article (id) where image_status = 'PENDING';

-- 중요도·언급 대상: AI 가 제목으로 판단 (큰 소식을 앞에 보여 주고, 사소한 고위험 CVE 는 알리지 않는 기준)
alter table article
    -- ArticleImportance: HEADLINE(널리 쓰는 제품의 악용·대규모 사고), NOTABLE(주목할 소식), ROUTINE(그 밖)
    add column importance    varchar(16) not null default 'ROUTINE',
    -- 제목에 나온 회사·제품 이름 (제목에 그대로 있는 글자만, 없으면 null)
    add column subject_name  varchar(80);

-- 주요 소식 조회: 중요도 있는 기사만 최신순
create index idx_article_importance_published_at on article (importance, published_at desc)
    where importance <> 'ROUTINE';

-- 최근 2주 기사는 중요도·언급 대상을 받도록 AI 대기로 되돌림
update article
   set ai_status = 'PENDING', ai_attempt_count = 0
 where published_at >= now() - interval '14 days' and ai_status <> 'PENDING';

