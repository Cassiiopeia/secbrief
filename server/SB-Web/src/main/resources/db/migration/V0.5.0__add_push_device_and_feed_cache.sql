-- AI 가 제목에서 뽑은 키워드 (해시태그 모아 보기·검색, 기사당 최대 5개)
create table article_keyword (
    article_id  bigint      not null references article (id) on delete cascade,
    keyword     varchar(40) not null,
    primary key (article_id, keyword)
);

-- 키워드별 기사 조회·인기 키워드 집계 (조회는 대소문자를 무시하므로 소문자 기준)
create index idx_article_keyword_lower_keyword on article_keyword (lower(keyword));

-- 제목 임베딩 (의미 검색): 확장 없이 쓰려고 real 배열로 보관, 비교는 서버가 계산
create table article_embedding (
    article_id       bigint       primary key references article (id) on delete cascade,
    -- 임베딩 모델 이름 (모델을 바꾸면 다시 만들어야 함)
    embedding_model  varchar(100) not null,
    embedding        real[]       not null,
    created_at       timestamptz  not null default now()
);

-- 앱 안 상세(브리프): AI 요약 + 원문에 있는 사실 값 (본문은 보관하지 않고 요약 입력만 잠시 둠)
alter table article
    -- AI 요약 입력: 피드가 준 요약문·공개 취약점 설명 (요약이 끝나거나 최종 실패하면 비움)
    add column source_text            text,
    -- AI 가 쓴 한국어 요약 (입력에 없는 숫자가 있으면 저장하지 않음)
    add column summary                varchar(1500),
    -- 핵심 정리 (JSON 문자열 배열)
    add column summary_key_points     text,
    -- 대응 안내: 입력에 적힌 조치만 (없으면 null)
    add column summary_action_guide   varchar(800),
    -- SummaryStatus: NONE(요약할 입력 없음), PENDING, DONE, FAILED
    add column summary_status         varchar(16) not null default 'NONE',
    add column summary_attempt_count  int         not null default 0,
    -- 원문에 있는 사실 값 (JSON 배열 [{label, value}]: 영향 패키지·버전, 조치 버전, CISA 조치 기한 등 — AI 가 만들지 않음)
    add column source_facts           text;

-- 요약 대기열
create index idx_article_summary_pending on article (id) where summary_status = 'PENDING';
