-- 관리자 페이지 · 설정 저장소 · AI 호출 기록 · 이용 집계 (#40)
-- created_at/updated_at: BaseEntity(LocalDateTime, 서울 시각)와 맞춘 서울 시각 기본값

-- 관리자 계정 (초기 계정은 운영 설정 secbrief.admin.accounts 에서 기동 시 생성, 비밀번호는 BCrypt)
create table admin (
    id          bigint generated by default as identity primary key,
    username    varchar(50)  not null unique,
    password    varchar(100) not null,
    created_at  timestamp    not null default (now() at time zone 'Asia/Seoul'),
    updated_at  timestamp    not null default (now() at time zone 'Asia/Seoul')
);

-- 관리자 동작 기록 (누가 무엇을 바꿨는지, 비밀값은 남기지 않음)
create table admin_audit_log (
    id              bigint generated by default as identity primary key,
    admin_username  varchar(50)  not null,
    -- AdminAuditAction 이름
    action          varchar(50)  not null,
    target_type     varchar(50),
    target_id       varchar(100),
    detail          varchar(500),
    created_at      timestamptz  not null default now()
);

create index idx_admin_audit_log_created_at on admin_audit_log (created_at desc);

-- 운영 중 바꾸는 설정 (ConfigKey 이름 > 값). 비밀 종류(SECRET)는 AES-GCM 으로 암호화한 값만 저장
create table system_config (
    id            bigint generated by default as identity primary key,
    config_key    varchar(100) not null unique,
    config_value  text,
    created_at    timestamp    not null default (now() at time zone 'Asia/Seoul'),
    updated_at    timestamp    not null default (now() at time zone 'Asia/Seoul')
);

-- 설정 변경 이력 (비밀 종류는 값 대신 있음·없음 표시만)
create table system_config_history (
    id          bigint generated by default as identity primary key,
    config_key  varchar(100) not null,
    old_value   text,
    new_value   text,
    changed_by  varchar(50)  not null,
    reason      varchar(500),
    created_at  timestamptz  not null default now()
);

create index idx_system_config_history_key_created_at on system_config_history (config_key, created_at desc);

-- AI 호출 기록 (추이·비용 추정·키별 상태 확인용, 입력 글·키 값은 남기지 않음)
create table ai_call_log (
    id                  bigint generated by default as identity primary key,
    -- AiCallType: TITLE_ANALYSIS, SUMMARY
    call_type           varchar(32)   not null,
    -- 제공자 코드 (anthropic, ollama)
    provider            varchar(32)   not null,
    model               varchar(100),
    -- 쓴 키의 별명 (키 값 아님, 운영 설정의 키면 'config')
    key_label           varchar(50),
    is_success          boolean       not null,
    -- 실패 종류 (정리된 짧은 코드)
    failure_reason      varchar(100),
    latency_ms          int,
    input_tokens        int,
    output_tokens       int,
    estimated_cost_usd  numeric(12, 6),
    created_at          timestamptz   not null default now()
);

create index idx_ai_call_log_created_at on ai_call_log (created_at desc);

-- 일별 이용 집계 (개인 식별값 없이 요청 건수만): 화면 묶음별 하루 1행
create table api_usage_daily (
    -- 서울 날짜
    usage_date     date         not null,
    -- ApiUsageGroup 이름 (TODAY, ARTICLE_LIST, ARTICLE_DETAIL, SEARCH, KEYWORD, PUSH_DEVICE ...)
    usage_group    varchar(32)  not null,
    request_count  bigint       not null default 0,
    primary key (usage_date, usage_group)
);

-- 관리자 대시보드: 오늘·이번 주 수집 건수와 수집 추이가 collected_at 기간으로 조회
create index idx_article_collected_at on article (collected_at);

-- AI 제목 분석 대기열: 게시일 최신순으로 읽음 (대기 건만 담는 부분 인덱스)
create index idx_article_ai_pending_published_at on article (published_at desc, id desc) where ai_status = 'PENDING';

-- AI 호출 화면: 용도·성공 여부로 걸러 최신순으로 봄
create index idx_ai_call_log_call_type_id on ai_call_log (call_type, id desc);
