-- 알림함(긴급 알림 기록·공지사항) · 기기별 방해 금지 시간 · 방해 금지 시간에 보류한 푸시 (#70)

-- 알림함 1건: NotificationKind ALERT(긴급 알림 발송 기록, 30일 보관) / NOTICE(관리자가 쓴 공지사항, 지울 때까지 보관)
create table notification (
    id              bigint generated by default as identity primary key,
    -- NotificationKind: ALERT, NOTICE
    kind            varchar(16)   not null,
    -- ALERT 의 대표 알림 종류 (AlertCategory: KISA_URGENT, KEV, CRITICAL_CVE), NOTICE 는 null
    alert_category  varchar(32),
    title           varchar(200)  not null,
    -- ALERT: 보낸 알림 본문, NOTICE: 공지 본문 (줄바꿈 그대로)
    body            text          not null,
    -- NOTICE 의 선택 링크 (http·https 만)
    link_url        varchar(1000),
    -- NOTICE 상단 고정 (ALERT 는 항상 false)
    is_pinned       boolean       not null default false,
    -- 푸시를 처음 보낸 시각 (방해 금지 시간으로 모두 보류 중이거나 푸시 없이 올린 공지는 null)
    pushed_at       timestamptz,
    created_at      timestamptz   not null default now(),
    updated_at      timestamptz   not null default now()
);

-- 알림함 목록: 종류별 고정 먼저 > 최신순 (커서 페이지)
create index idx_notification_kind_list on notification (kind, is_pinned desc, created_at desc, id desc);

-- 긴급 알림 1건에 묶인 기사 (알림 순서대로, 기사가 지워지면 함께 지움)
create table notification_article (
    notification_id  bigint      not null references notification (id) on delete cascade,
    -- 알림 안 순서 (0부터)
    position         int         not null,
    article_id       bigint      not null references article (id) on delete cascade,
    -- 이 기사의 알림 종류 (AlertCategory)
    alert_category   varchar(32) not null,
    primary key (notification_id, position)
);

-- 방해 금지 시간: 기기 시간대 기준 [시작, 끝) (끝이 시작보다 이르면 다음 날까지), 기존 기기는 꺼짐
alter table push_device
    add column is_quiet_hours_enabled  boolean     not null default false,
    add column quiet_hours_start_time  time        not null default '22:00',
    add column quiet_hours_end_time    time        not null default '08:00',
    -- IANA 시간대 이름 (예: Asia/Seoul)
    add column time_zone               varchar(64) not null default 'Asia/Seoul';

-- 방해 금지 시간에 보류한 푸시 1건 (끝나면 1건이면 그대로, 여러 건이면 모아 1건 보내고 삭제)
create table push_device_held_push (
    id                 bigint generated by default as identity primary key,
    push_device_id     bigint       not null references push_device (id) on delete cascade,
    notification_id    bigint       not null references notification (id) on delete cascade,
    -- NotificationKind: ALERT, NOTICE
    notification_kind  varchar(16)  not null,
    title              varchar(200) not null,
    body               varchar(500) not null,
    -- 기사 1건 알림이면 그 기사 번호 (앱이 상세를 엶)
    article_id         bigint,
    -- 이 푸시가 알린 기사 수 (NOTICE 는 0)
    article_count      int          not null default 0,
    held_at            timestamptz  not null
);

create index idx_push_device_held_push_device on push_device_held_push (push_device_id, id);
