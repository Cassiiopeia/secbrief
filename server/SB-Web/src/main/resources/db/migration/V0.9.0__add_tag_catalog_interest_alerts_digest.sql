-- 분류 태그 카탈로그 · 기사 분류 열 · 기기 관심 기술 · 아침 요약 (#93), 알림 후보 대기 (#97)

-- 분류 태그 1개: 관리자 화면에서 추가·이름 바꾸기·순서·숨김, 기사·기기는 code 만 저장
create table catalog_tag (
    id               bigint generated by default as identity primary key,
    -- CatalogTagKind: FIELD 기술 분야, ECOSYSTEM 오픈소스 생태계, PRODUCT_GROUP 관심 기술 인기 묶음, PRODUCT 제품·회사·패키지
    kind             varchar(16)   not null,
    -- 바뀌지 않는 값 (소문자·숫자·-), kind 안에서 유일
    code             varchar(64)   not null,
    name             varchar(80)   not null,
    -- 칩·태그용 짧은 이름
    short_name       varchar(40)   not null,
    -- PRODUCT 의 인기 묶음 (PRODUCT_GROUP code, 없으면 검색으로만)
    group_code       varchar(64),
    -- PRODUCT 의 기술 분야 (FIELD code)
    field_code       varchar(64),
    -- 분류 낱말 (쉼표 구분, 소문자 비교·낱말 경계 일치, ~ 로 시작하면 약한 낱말), ECOSYSTEM 은 GitHub ecosystem 원문 값
    match_terms      text          not null default '',
    -- 주요 판정의 널리 쓰는 제품 (PRODUCT 만)
    is_widely_used   boolean       not null default false,
    -- 숨기면 API·분류·관심 판정에서 빠짐
    is_visible       boolean       not null default true,
    display_order    int           not null default 0,
    created_at       timestamp     not null default (now() at time zone 'Asia/Seoul'),
    updated_at       timestamp     not null default (now() at time zone 'Asia/Seoul'),
    unique (kind, code)
);

-- 기사 분류 열 (CPE·패키지·제품 사전 > 분야 낱말 > AI 분야 > other)
alter table article
    add column field_code      varchar(64),
    add column ecosystem_code  varchar(64),
    -- GitHub 권고 첫 패키지 이름 (원문 그대로)
    add column package_name    varchar(200),
    add column product_code    varchar(64),
    -- AI 가 제목 분석에서 고른 분야 (규칙으로 못 정할 때만 씀)
    add column ai_field_code   varchar(64),
    -- ClassificationSource: PRODUCT, KEYWORD, AI, NONE
    add column field_source    varchar(16),
    add column is_notable      boolean     not null default false,
    -- 분류한 시각 (null: 분류 대기, 백필·다시 분류 대상)
    add column classified_at   timestamptz;

create index idx_article_unclassified on article (id) where classified_at is null;
create index idx_article_field_published_at on article (field_code, published_at desc);
create index idx_article_ecosystem_published_at on article (ecosystem_code, published_at desc) where ecosystem_code is not null;

-- urgent_notified_at 은 이제 알림 처리 시각 (긴급 아님도 관심 판정): 긴급이 아닌 기존 행은 처리됨으로
update article set urgent_notified_at = now() where urgent_notified_at is null and is_urgent = false;
drop index if exists idx_article_urgent_unnotified;
create index idx_article_alert_unprocessed on article (id) where urgent_notified_at is null;

-- 기기 알림 받는 방식: AlertDeliveryMode IMMEDIATE 바로 / DIGEST 아침 요약 (긴급이 아닌 관심 소식), 요약 시각은 기기 시간대
alter table push_device
    add column alert_delivery_mode  varchar(16) not null default 'DIGEST',
    add column digest_time          time        not null default '08:00',
    -- 마지막 아침 요약을 보낸 기기 날짜 (하루 1번)
    add column last_digest_date     date;

-- 그 밖의 고위험(CRITICAL_CVE) 기본 꺼짐: 세 종류를 모두 켠(이전 기본값) 기기만 끔, 직접 고른 조합은 유지
delete from push_device_alert_category c
 where c.alert_category = 'CRITICAL_CVE'
   and (select count(*) from push_device_alert_category o where o.push_device_id = c.push_device_id) = 3;

-- 기기 관심 기술 (CatalogTagKind PRODUCT·FIELD·ECOSYSTEM + code)
create table push_device_interest (
    push_device_id  bigint      not null references push_device (id) on delete cascade,
    kind            varchar(16) not null,
    code            varchar(64) not null,
    primary key (push_device_id, kind, code)
);

-- 아침 요약 대기 기사 (요약을 보내면 지움, 48시간 지나면 버림)
create table push_device_digest_item (
    push_device_id  bigint      not null references push_device (id) on delete cascade,
    article_id      bigint      not null references article (id) on delete cascade,
    queued_at       timestamptz not null,
    primary key (push_device_id, article_id)
);

-- 기기 1대 전용 알림 기록 (DIGEST 아침 요약, 관심만 맞은 여러 건 바로 알림): 알림함 목록에 보이지 않음
alter table notification
    add column push_device_id bigint references push_device (id) on delete cascade;
drop index if exists idx_notification_kind_list;
create index idx_notification_kind_list on notification (kind, is_pinned desc, created_at desc, id desc) where push_device_id is null;

